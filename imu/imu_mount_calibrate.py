#!/usr/bin/env python3
"""Solve the sensor->model mount quaternion from three gravity poses.

Uses only the raw accelerometer (mean specific force per pose), so Madgwick's
free yaw cannot contaminate the solve:

  Pose A  flat, SCREEN UP, USB-C toward you   -> model +Z = normalize(accA)
  Pose B  flat, SCREEN DOWN, USB-C toward you  -> checks -accB || +accA
  Pose C  held UPRIGHT, screen facing you, USB-C at the TOP
          (cable hanging down)             -> model +Y = -normalize(accC)

Model +X = +Y (x) +Z (right-handed).  M = R_sensor<-model.
Writes imu_stream/mount_quat.h (MOUNT_W/X/Y/Z) for imu_stream.ino.
"""
import os
import subprocess
import sys
import time

import numpy as np
import serial

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = "/dev/ttyACM0"


def q_from_matrix(R):
    R00, R01, R02 = R[0]
    R10, R11, R12 = R[1]
    R20, R21, R22 = R[2]
    t = R00 + R11 + R22
    if t > 0:
        s = np.sqrt(t + 1.0) * 2
        w = 0.25 * s
        x = (R21 - R12) / s
        y = (R02 - R20) / s
        z = (R10 - R01) / s
    elif R00 > R11 and R00 > R22:
        s = np.sqrt(1.0 + R00 - R11 - R22) * 2
        w = (R21 - R12) / s
        x = 0.25 * s
        y = (R01 + R10) / s
        z = (R02 + R20) / s
    elif R11 > R22:
        s = np.sqrt(1.0 + R11 - R00 - R22) * 2
        w = (R02 - R20) / s
        x = (R01 + R10) / s
        y = 0.25 * s
        z = (R12 + R21) / s
    else:
        s = np.sqrt(1.0 + R22 - R00 - R11) * 2
        w = (R10 - R01) / s
        x = (R02 + R20) / s
        y = (R12 + R21) / s
        z = 0.25 * s
    return np.array([w, x, y, z]) / np.linalg.norm([w, x, y, z])


def capture_acc(s, seconds=6):
    """Mean accelerometer vector (g) over `seconds`, skipping first 20%."""
    data = []
    t0 = time.time()
    while time.time() - t0 < seconds:
        line = s.readline().decode(errors="ignore").strip()
        p = line.split(",")
        if len(p) == 11 and p[0].isdigit():
            data.append([float(x) for x in p[1:4]])
    if not data:
        sys.exit("no samples — is the firmware flashed and the port free?")
    settle = len(data) // 5
    arr = np.array(data[settle:])
    return np.round(arr.mean(0), 5), len(data)


def pose(name, instruction, s, secs=6):
    print(f"\n=== {name} ===\n{instruction}")
    input("Press ENTER when the board is steady in this pose... ")
    print("  capturing 6 s — hold steady    ", flush=True)
    acc, n = capture_acc(s, secs)
    mag = np.linalg.norm(acc)
    print(f"  ok: {n} samples | acc = {acc} | |a| = {mag:.3f}")
    if abs(mag - 1.0) > 0.15:
        print("  WARN: |a| far from 1 — keep the board still, flat, away from metal")
    return acc


def main():
    subprocess.run(["fuser", "-k", "8765/tcp"], capture_output=True)
    time.sleep(1)
    s = serial.Serial(PORT, 115200, timeout=1)
    s.dtr = True
    s.rts = False
    time.sleep(1.5)
    s.reset_input_buffer()

    accA = pose("Pose A",
        "Board FLAT on the table, SCREEN FACING UP, USB-C pointing TOWARD YOU.", s)
    accB = pose("Pose B",
        "Flip it onto its BACK — SCREEN FACING DOWN, USB-C still TOWARD YOU.", s)
    accC = pose("Pose C",
        "HOLD the board UPRIGHT, SCREEN FACING YOU, USB-C CONNECTOR AT THE TOP\n"
        "  (cable hanging loosely down). Keep it as vertical as you can.", s)
    s.close()

    # Two-position bias extraction: A/B are the same pose +/- g, so
    # (accA-accB)/2 is the gravity vector, (accA+accB)/2 is the accel bias.
    gravity = (accA - accB) / 2
    bias = (accA + accB) / 2
    print(f"\naccel bias (g) = {np.round(bias, 3)}")

    zA = accA / np.linalg.norm(accA)
    yC = -(accC - bias) / np.linalg.norm(accC - bias)  # USB up => model +Y points down

    z = gravity / np.linalg.norm(gravity)               # unbiased screen-up direction

    ang_yA = np.degrees(np.arccos(np.clip(np.dot(yC, z), -1, 1)))
    print("\nchecks:")
    print(f"  y(C) vs z(A,B):    {ang_yA:5.1f} deg  (expect ~90)"
          f"  {'OK' if 75 < ang_yA < 105 else 'BAD — redo'}")
    if not 75 < ang_yA < 105:
        sys.exit("pose check failed — rerun calibration, hold steady")

    y = yC - z * np.dot(yC, z)          # Gram-Schmidt: y perpendicular to z
    y /= np.linalg.norm(y)
    x = np.cross(y, z)
    x /= np.linalg.norm(x)

    R = np.column_stack([x, y, z])      # columns: model axes in sensor frame
    M = q_from_matrix(R)
    if M[0] < 0:
        M = -M

    print("\n=== RESULT ===")
    print(f"model axes in sensor frame:\n  x = {np.round(x, 3)}\n  y = {np.round(y, 3)}\n  z = {np.round(z, 3)}")
    print(f"mount quaternion M (sensor->model) = {np.round(M, 5).tolist()}")

    with open(os.path.join(HERE, "imu_stream", "mount_quat.h"), "w") as f:
        f.write("// Generated by imu_mount_calibrate.py — sensor->model mount quaternion\n")
        f.write(f"#define MOUNT_W  {M[0]:.9f}f\n#define MOUNT_X  {M[1]:.9f}f\n")
        f.write(f"#define MOUNT_Y  {M[2]:.9f}f\n#define MOUNT_Z  {M[3]:.9f}f\n")
    print("wrote imu_stream/mount_quat.h  — now ask me to compile + flash it")

    subprocess.run(["fuser", "-k", "8765/tcp"], capture_output=True)
    subprocess.Popen(
        ["setsid", "nohup", sys.executable, os.path.join(HERE, "imu_server.py")],
        stdout=open(os.path.join(HERE, "server.log"), "w"),
        stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL)
    print("server restarted")


if __name__ == "__main__":
    main()
